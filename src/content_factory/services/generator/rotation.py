"""Cursor of the last appearance card generated successfully for a profile.

The cursor lives next to the run directories of one ``language + profile``
pair, so a batch can continue with the card that follows the last successful
one across runs. It is a single capsule: when the cursor moves to a database,
only this module changes.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from loguru import logger

ROTATION_FILENAME = "rotation.json"


def read_cursor(path: Path) -> str | None:
    """Read the id of the last successfully generated appearance card.

    A missing file is the normal first-run state and is not logged. A broken
    file is logged as a warning and treated as absent, so the next batch
    starts from the first card and rewrites the cursor on its first success.

    Args:
        path: Path of ``rotation.json``.

    Returns:
        ``last_look_id`` from the file or ``None`` when it cannot be used.
    """
    try:
        raw = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None
    except OSError as ex:
        _warn(path, f"не удалось прочитать файл: {ex}", ex)
        return None
    try:
        payload: Any = json.loads(raw)
    except json.JSONDecodeError as ex:
        _warn(path, f"битый JSON: {ex}", ex)
        return None
    if not isinstance(payload, dict):
        _warn(path, f"ожидался JSON-объект, получено {type(payload).__name__}")
        return None
    look_id = payload.get("last_look_id")
    if not isinstance(look_id, str):
        _warn(path, f"поле last_look_id должно быть строкой, получено {type(look_id).__name__}")
        return None
    return look_id


def read_profile_cursor(output_dir: Path, language: str, slug: str) -> str | None:
    """Return the cursor of one ``language + profile`` output directory.

    Args:
        output_dir: Root of the run directories.
        language: Language folder of the profile.
        slug: Profile slug folder used in output paths.

    Returns:
        ``last_look_id`` from the rotation cursor, or ``None`` when it is
        missing or unusable.
    """
    return read_cursor(output_dir / language / slug / ROTATION_FILENAME)


def advance_cursor(path: Path, last_look_id: str, run_id: str, now: datetime) -> None:
    """Move the cursor to *last_look_id*, writing the file atomically.

    The temporary file is created in the same directory as the cursor, so the
    final rename stays atomic on one filesystem and a reader never sees a
    half-written JSON. The directory is created when missing.

    Args:
        path: Path of ``rotation.json``.
        last_look_id: Id of the card generated by the finished video.
        run_id: Identifier of the run that produced the video.
        now: Moment of the update, stored as ISO-8601 UTC.
    """
    payload = {
        "last_look_id": last_look_id,
        "run_id": run_id,
        "updated_at": now.astimezone(UTC).isoformat(),
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f"{path.name}.tmp")
    temporary.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    temporary.replace(path)


def _warn(path: Path, reason: str, error: Exception | None = None) -> None:
    """Log an unusable cursor with its path and reason."""
    context = logger.bind(path=str(path), reason=reason)
    if error is None:
        context.warning("Курсор карточек не прочитан")
    else:
        context.bind(error=str(error), error_type=type(error).__name__).warning(
            "Курсор карточек не прочитан"
        )
