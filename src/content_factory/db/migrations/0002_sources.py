"""Source pool of a profile and its circular cursor.

The migration adds two tables: the imported source files with their metadata
and the cursor of the last source used by a successful batch. Both backends
share the column types; only the autoincrement spelling of the primary key
differs between SQLite and PostgreSQL.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from content_factory.schemas.database.port import Connection

VERSION = "0002"

_SOURCE_ITEMS_SQLITE = """
CREATE TABLE IF NOT EXISTS source_items (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    language TEXT NOT NULL,
    profile_id TEXT NOT NULL,
    path TEXT NOT NULL UNIQUE,
    sha256 TEXT NOT NULL,
    size INTEGER NOT NULL,
    duration REAL NOT NULL,
    added_at TEXT NOT NULL,
    used_at TEXT,
    use_count INTEGER NOT NULL DEFAULT 0,
    missing_at TEXT,
    UNIQUE(language, profile_id, sha256)
)
"""

_SOURCE_ITEMS_POSTGRES = """
CREATE TABLE IF NOT EXISTS source_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    language TEXT NOT NULL,
    profile_id TEXT NOT NULL,
    path TEXT NOT NULL UNIQUE,
    sha256 TEXT NOT NULL,
    size INTEGER NOT NULL,
    duration REAL NOT NULL,
    added_at TEXT NOT NULL,
    used_at TEXT,
    use_count INTEGER NOT NULL DEFAULT 0,
    missing_at TEXT,
    UNIQUE(language, profile_id, sha256)
)
"""

_SOURCE_CURSORS = """
CREATE TABLE IF NOT EXISTS source_cursors (
    language TEXT NOT NULL,
    profile_id TEXT NOT NULL,
    last_source_id INTEGER,
    updated_at TEXT NOT NULL,
    PRIMARY KEY (language, profile_id)
)
"""

_SOURCE_INDEX = """
CREATE INDEX IF NOT EXISTS idx_source_items_pool
ON source_items(language, profile_id, missing_at, id)
"""


def apply(connection: Connection) -> None:
    """Create the source pool and cursor tables.

    Args:
        connection: Open connection whose backend is SQLite or PostgreSQL.
    """
    items = _SOURCE_ITEMS_POSTGRES if connection.dialect == "postgres" else _SOURCE_ITEMS_SQLITE
    connection.execute(items)
    connection.execute(_SOURCE_CURSORS)
    connection.execute(_SOURCE_INDEX)


__all__ = ["VERSION", "apply"]
